from pathlib import Path
from typing import Any, Dict
import json
import joblib
import pandas as pd
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
MODEL_PATH = ROOT / "models" / "student_outcome_logistic_regression.pkl"
DATA_PATH = ROOT / "data" / "data.csv"

LABELS = ["Dropout", "Enrolled", "Graduate"]

CATEGORICAL_FEATURES = [
    "Marital status", "Application mode", "Application order", "Course",
    "Daytime/evening attendance\t", "Previous qualification", "Nacionality",
    "Mother's qualification", "Father's qualification", "Mother's occupation",
    "Father's occupation", "Displaced", "Educational special needs", "Debtor",
    "Tuition fees up to date", "Gender", "Scholarship holder", "International"
]

NUMERICAL_FEATURES = [
    "Previous qualification (grade)", "Admission grade", "Age at enrollment",
    "Curricular units 1st sem (credited)", "Curricular units 1st sem (enrolled)",
    "Curricular units 1st sem (evaluations)", "Curricular units 1st sem (approved)",
    "Curricular units 1st sem (grade)", "Curricular units 1st sem (without evaluations)",
    "Unemployment rate", "Inflation rate", "GDP"
]

class PredictionRequest(BaseModel):
    features: Dict[str, Any]

app = FastAPI(title="Data Speaks Prediction API", version="1.0.0")
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:5173", "http://127.0.0.1:5173"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

_model = None
_defaults = None

def load_resources():
    global _model, _defaults
    if _model is None:
        if not MODEL_PATH.exists():
            raise FileNotFoundError(f"Model not found: {MODEL_PATH}")
        _model = joblib.load(MODEL_PATH)

    if _defaults is None:
        if DATA_PATH.exists():
            df = pd.read_csv(DATA_PATH, sep=";")
            _defaults = {c: df[c].mode(dropna=True).iloc[0] for c in CATEGORICAL_FEATURES}
            for c in NUMERICAL_FEATURES:
                _defaults[c] = float(df[c].median())
        else:
            # Fallback values are project-derived medians/modes; replace with data/data.csv for full local reproducibility.
            _defaults = {
                "Marital status":1,"Application mode":1,"Application order":1,"Course":9500,
                "Daytime/evening attendance\t":1,"Previous qualification":1,"Nacionality":1,
                "Mother's qualification":1,"Father's qualification":37,"Mother's occupation":9,
                "Father's occupation":9,"Displaced":1,"Educational special needs":0,"Debtor":0,
                "Tuition fees up to date":1,"Gender":0,"Scholarship holder":0,"International":0,
                "Previous qualification (grade)":133.1,"Admission grade":126.1,"Age at enrollment":20,
                "Curricular units 1st sem (credited)":0,"Curricular units 1st sem (enrolled)":6,
                "Curricular units 1st sem (evaluations)":8,"Curricular units 1st sem (approved)":5,
                "Curricular units 1st sem (grade)":12.285714,"Curricular units 1st sem (without evaluations)":0,
                "Unemployment rate":11.1,"Inflation rate":1.4,"GDP":0.32
            }
    return _model, _defaults

@app.get("/api/health")
def health():
    try:
        load_resources()
        return {"status":"ok","model":"loaded"}
    except Exception as exc:
        return {"status":"error","model":"unavailable","detail":str(exc)}

@app.get("/api/metadata")
def metadata():
    return {
        "target_classes": LABELS,
        "classification_features": CATEGORICAL_FEATURES + NUMERICAL_FEATURES,
        "numeric_features": NUMERICAL_FEATURES,
        "note": "The classification pipeline uses 30 input features. The six second-semester fields are used in the project's K-Means/PCA analysis, not in this saved classification pipeline."
    }

@app.post("/api/predict")
def predict(req: PredictionRequest):
    try:
        model, defaults = load_resources()
        row = defaults.copy()
        for key, value in req.features.items():
            if key not in NUMERICAL_FEATURES:
                continue
            row[key] = float(value)
        X = pd.DataFrame([row], columns=CATEGORICAL_FEATURES + NUMERICAL_FEATURES)
        pred = int(model.predict(X)[0])
        probs = model.predict_proba(X)[0]
        probabilities = {LABELS[i]: float(probs[i]) for i in range(len(LABELS))}
        return {
            "prediction": LABELS[pred],
            "probabilities": probabilities,
            "message": "Prediction generated by the saved project Logistic Regression pipeline."
        }
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Model prediction could not be completed: {exc}")

if __name__ == "__main__":
    import uvicorn
    uvicorn.run("app:app", host="127.0.0.1", port=8000, reload=False)
